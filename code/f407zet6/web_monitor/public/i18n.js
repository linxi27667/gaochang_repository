let currentLang = localStorage.getItem('lift_lang') || 'zh';

function t(key) {
  const lang = I18N[currentLang] || I18N['zh'];
  return lang[key] || I18N['zh'][key] || key;
}

function setLang(lang) {
  if (!LANGUAGES[lang]) lang = 'zh';
  currentLang = lang;
  localStorage.setItem('lift_lang', lang);
  applyLang();
  // Fully reload current page including async data (only when app is active)
  if (typeof loadPage === 'function' && document.getElementById('app') && document.getElementById('app').style.display !== 'none') {
    loadPage(currentPage);
  }
  // Close all dropdowns
  const dd1 = document.getElementById('lang-menu');
  const dd2 = document.getElementById('login-lang-dropdown');
  if (dd1) dd1.style.display = 'none';
  if (dd2) dd2.style.display = 'none';
}

function applyLang() {
  const langInfo = LANGUAGES[currentLang] || LANGUAGES['zh'];
  document.documentElement.lang = currentLang;
  document.documentElement.dir = langInfo.dir;

  // Update text content
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const text = t(key);
    if (text && text !== key) el.textContent = text;
  });
  // Update placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const text = t(key);
    if (text && text !== key) el.placeholder = text;
  });

  // Update lang labels
  const label = document.getElementById('current-lang-label');
  if (label) label.textContent = langInfo.label;
  const loginLabel = document.getElementById('login-lang-label');
  if (loginLabel) loginLabel.textContent = langInfo.label;

  // Update page title
  document.title = t('app.name');
}

function toggleLangMenu() {
  const menu = document.getElementById('lang-menu');
  if (!menu) return;
  const visible = getComputedStyle(menu).display !== 'none';
  menu.style.display = visible ? 'none' : 'block';
}

function showLangDropdown() {
  const dd = document.getElementById('login-lang-dropdown');
  if (!dd) return;
  const visible = getComputedStyle(dd).display !== 'none';
  dd.style.display = visible ? 'none' : 'block';
}

// Close lang menu on outside click
document.addEventListener('click', (e) => {
  const langMenu = document.getElementById('lang-menu');
  if (langMenu && getComputedStyle(langMenu).display !== 'none' && !e.target.closest('.lang-switcher')) {
    langMenu.style.display = 'none';
  }
  const loginLangDD = document.getElementById('login-lang-dropdown');
  if (loginLangDD && getComputedStyle(loginLangDD).display !== 'none' && !e.target.closest('.lang-switch-login')) {
    loginLangDD.style.display = 'none';
  }
});
